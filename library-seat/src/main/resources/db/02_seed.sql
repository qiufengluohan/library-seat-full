--           System.out.println(new BCryptPasswordEncoder().encode("你的新密码"));
--      2) UPDATE admin_user SET password = '<新哈希>' WHERE username = 'admin';
--    改完密码后本文件再执行也不会把它覆盖回去（INSERT IGNORE 只在行不存在时插入）。
